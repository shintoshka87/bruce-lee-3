def pull_pair(s_sets, p_sets):
    """Когда делать «занос за голову» относительно подходов приседаний."""
    if p_sets == 1:
        return 'сразу после последнего подхода приседаний'
    if p_sets >= s_sets:
        return 'после каждого подхода приседаний'
    first = s_sets - p_sets + 1
    nums = [f'{i}-го' for i in range(first, s_sets + 1)]
    return 'после ' + ' и '.join([', '.join(nums[:-1]), nums[-1]] if len(nums) > 2 else nums) + ' подходов приседаний'



def info(c):
    for b, a, z in BLOCKS:
        if a <= c <= z:
            i = c - a
            w = (WAVES_B6 if b == 6 else WAVES_STD)[i]
            return {'c': c, 'b': b, 'i': i, 'w': w, 'cx': 1 if b % 2 else 2, 'L': (b + 1) // 2,
                    'test': c in TEST_CYCLES, 'first': c == a, 'last': c == z}
    raise ValueError(c)


def dn(c, k):
    return (c - 1) * 4 + k


def week(d):
    return (d - 1) // 7 + 1



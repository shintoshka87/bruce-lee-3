EXWT = {}  # тип веса упражнения: заполняет appdata/docgen из exercises.py
def _tempo_s(t):
    if not t:
        return 3
    return sum(1 if x == 'X' else int(x) for x in t.split('-'))


def set_seconds(it):
    sides = 2 if it.get('per') in ('на сторону', 'на ногу', 'каждой рукой') else 1
    if it['unit'] == 'sec':
        if it.get('rows'):
            return sum(k * it['hi'] + (k - 1) * rr for k, rr in it['rows']) / len(it['rows'])
        if it.get('hold'):
            k, rr = it['hold']
            return k * (it['hi'] * (2 if it.get('lr') else 1) + rr * (2 if it.get('lr') else 1))
        return it['hi'] * (2 if it.get('lr') else 1) + (10 if it.get('lr') else 0)
    reps = (it['lo'] + it['hi']) / 2
    t = reps * _tempo_s(it.get('tempo')) * sides
    if it.get('cluster'):
        t += 2 * 20
    return t


def est_seconds(items):
    tot = 0
    for it in items:
        if it['t'] == 'cond':
            tot += sum(s['s'] for s in it['segs'])
        elif it['t'] == 'ex':
            wt = it.get('wt') or EXWT.get(it['id'], 'bw')
            tot += it['n'] * (set_seconds(it) + it['rest']) + (30 if wt in ('mc', 'pl', 'sm', 'bar', 'db', 'kb', 'gv') else 10)
    return tot


def warm_seconds(steps):
    tot = 0
    for st in steps:
        tot += sum(s['s'] for s in st.get('segs', [])) or (150 if st.get('ramp') else 90)
    return tot

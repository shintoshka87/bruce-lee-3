def cycle_md(c):
    P, m, mp, w = info(c)
    a, b = dn(c, 1), dn(c, 4)
    intro = [WAVE[w]]
    if w == 4 and c not in (29, 44):
        intro.append(STEP[P])
    if c in (15, 30):
        intro.append(f'Конец фазы: тесты в Дни {dn(c, 3)}–{dn(c, 4)} и решение о переходе; прыжки и предельные попытки в эти дни — только в самих тестах.')
    if c == 45:
        intro.append(f'Последний цикл программы: итоговые тесты в Дни {dn(c, 3)}–{dn(c, 4)}; прыжки и предельные попытки в эти дни — только в самих тестах.')
    if c in DIET:
        intro.append('Диет-брейк: все 4 дня — питание на поддержании, около +500 ккал за счёт углеводов к среднему дню. Вес может подняться на 0,5–1 кг за счёт воды — это запланировано.')
    if c == 29:
        intro.append(f'Шаг вперёд — проверка ворот в День {dn(c, 4)}: 5 раундов по 3 мин на груше; веса в силовой — из таблицы.')
    if c == 44:
        intro.append(f'Шаг вперёд — контрольная тренировка по личной программе Ли в День {dn(c, 4)}: в раунде «скорость и ещё раз скорость» — рекордный темп.')
    d3, m3 = day3(c)
    d4, m4 = day4(c)
    days = [d3, '', d4] if c in TEST else [d4, '', d3]
    parts = [f'## Цикл {c} · дни {a}–{b}', '', ' '.join(intro), '', shift_day(c, 1), '', shift_day(c, 2), ''] + days
    return '\n'.join(parts), m3, m4



def label_items(items):
    n, cur, seen = 0, None, {}
    for it in items:
        if it['t'] != 'ex':
            if it['t'] == 'hdr':
                cur = None
            continue
        g = it.get('grp')
        if g and g == cur:
            seen[g] += 1
            it['lab'] = f'{n}' + 'abc'[seen[g]]
        else:
            n += 1
            cur = g
            if g:
                seen[g] = 0
                it['lab'] = f'{n}a'
            else:
                it['lab'] = str(n)
    return items


def sets_text(it):
    n, lo, hi = it['n'], it['lo'], it['hi']
    per = (' ' + it['per']) if it.get('per') else ''
    if it.get('cluster'):
        return f'{n} × ({it["cluster"]})'
    if it['unit'] == 'sec':
        if it.get('rows'):
            return '-'.join(str(r[0]) for r in it['rows']) + f' × {hi} с'
        if it.get('hold'):
            k, _ = it['hold']
            return f'{n} × ({k} × {hi} с)' + (' на сторону' if it.get('lr') else '')
        return f'{n} × {hi} с' + (' на сторону' if it.get('lr') else '')
    if it.get('rows'):
        full = sum(1 for r in it['rows'] if r == 'full')
        return f'{full} × {rng(lo, hi)} + 1 × половина амплитуды' + per
    return f'{n} × {rng(lo, hi)}' + per



def ud(n):
    if n % 10 == 1 and n % 100 != 11:
        w = 'удар'
    elif 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        w = 'удара'
    else:
        w = 'ударов'
    return f'≈ {n} {w}'


def reletter(rows):
    out, i = [], 0
    for r in rows:
        b = r[0]
        if b:
            if len(b) > 3 and b[1] == '.' and b[2] == ' ':
                b = b[3:]
            b = f'{LET[i]}. {b}'
            i += 1
        out.append((b,) + tuple(r[1:]))
    return out


def table(rows, head=('Блок', 'Упражнение (страница книги)', 'Сколько', 'Как')):
    out = ['| ' + ' | '.join(head) + ' |', '| ' + ' | '.join(['---'] * len(head)) + ' |']
    for r in rows:
        out.append('| ' + ' | '.join(r) + ' |')
    return '\n'.join(out)



def zone(lo, hi, rhr=RHR, mx=HRMAX):
    """Нижняя граница — округление вверх от половины, верхняя — вниз: 114–125, 126–137, 137–148, 148–159, 159–170."""
    import math
    r = mx - rhr
    return math.floor(rhr + r * lo + 0.5), math.ceil(rhr + r * hi - 0.5)


def ztext(s, rhr=RHR, mx=HRMAX):
    """Подставляет зоны в текст — так же, как приложение."""
    for key, _, lo, hi in ZONES:
        a, b = zone(lo, hi, rhr, mx)
        s = s.replace('{' + key + '}', f'{a}–{b}')
    return s.replace('{CAP}', str(zone(0.9, 0.9, rhr, mx)[1]))


# ------------------------------------------------------------------ элементы тренировки
def seg(l, s, k='work', t=None):
    d = {'l': l, 's': int(round(s)), 'k': k}
    if t:
        d['t'] = t
    return d


def ex(i, n, lo, hi=None, rir=None, tempo=None, rest=0, per='', note='', unit='reps', load='', grp=None,
       hold=None, lr=False, cluster=None, rows=None, slow=False, sets=None):
    """Упражнение. hold=(n, rr) — n удержаний по hi с с отдыхом rr внутри строки; cluster='3+3+3'."""
    return {'t': 'ex', 'id': i, 'n': n, 'lo': lo, 'hi': hi if hi is not None else lo, 'rir': rir, 'tempo': tempo, 'rest': rest,
            'per': per, 'note': note, 'unit': unit, 'load': load, 'grp': grp, 'hold': hold, 'lr': lr, 'cluster': cluster,
            'rows': rows, 'slow': slow, 'sets': sets}


def cond(title, segs, lines=None, kind=None):
    return {'t': 'cond', 'title': title, 'segs': segs, 'lines': lines or [], 'kind': kind}


def hdr(text):
    return {'t': 'hdr', 'text': text}


def stretch(title, positions, H, how, kind='stretch'):
    """positions: [(название, стороны 1|2, секунды или None = H)]."""
    segs = []
    for j, (name, sides, sec) in enumerate(positions):
        s = sec or H
        if sides == 2:
            segs += [seg(name + ' — левая', s, 'work'), seg('Смена стороны', 5, 'rest'), seg(name + ' — правая', s, 'work')]
        else:
            segs.append(seg(name, s, 'work'))
        if j < len(positions) - 1:
            segs.append(seg('Переход', 8, 'rest'))
    return cond(title, segs, [how], kind)



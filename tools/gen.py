def pct(reps, rpe):
    row = TAB[reps]
    if rpe == 6: return row[7] - 3
    if rpe == int(rpe): return row[int(rpe)]
    lo, hi = int(math.floor(rpe)), int(math.ceil(rpe))
    return round((row[lo] + row[hi]) / 2)



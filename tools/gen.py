def main_lift(spec, show_pct=True):
    k = spec[0]
    if k == 's':
        _, n, r, rpe = spec
        load = "RPE " + fr(rpe)
        if show_pct and r in TAB: load += " · ≈%d%% от 1ПМ" % pct(r, rpe)
        return "%d × %d" % (n, r), load
    if k == 't':
        _, r, rpe, bn, br, drop = spec
        load = "топ на RPE %s" % fr(rpe)
        if show_pct and r in TAB: load += " (≈%d%%)" % pct(r, rpe)
        load += ", добивка −%d%% от топа" % drop
        return "1 × %d + %d × %d" % (r, bn, br), load
    if k == 'p':
        _, n, r, p = spec
        return "%d × %d" % (n, r), "≈%d%% от 1ПМ · RPE 6, штанга летит" % p



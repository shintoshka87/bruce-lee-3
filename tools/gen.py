def relabel(items):
    out, mp, n = [], {}, 0
    for i in items:
        if 'cond' in i or not i.get('lab'):
            out.append(i); continue
        m = re.match(r"(\d+)([ab]?)$", i['lab'])
        base, letter = m.group(1), m.group(2)
        if base not in mp:
            n += 1; mp[base] = n
        i['lab'] = str(mp[base]) + letter
        out.append(i)
    return out



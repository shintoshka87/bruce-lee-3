def name(it):
    return EX[it['id']]['name']


def pipe(rows):
    out = ['| ' + ' | '.join(rows[0]) + ' |', '| ' + ' | '.join('---' for _ in rows[0]) + ' |']
    out += ['| ' + ' | '.join(str(x) for x in r) + ' |' for r in rows[1:]]
    return '\n'.join(out)


def mins(sec):
    return int(5 * round(sec / 60 / 5)) if sec > 600 else int(round(sec / 60))


def cond_line(it):
    return f'{it["title"]}'


def tempo_or_hold(it):
    if it['id'] in ('suitcase', 'bottoms_up'):
        return 'ходьба'
    if it['unit'] == 'sec':
        if it.get('rows'):
            return 'удержания по 10 с'
        return f'удержания по {it["hi"]} с'
    return it.get('tempo') or ''


def simple_table(items, with_rir=True):
    rows = [['№', 'Упражнение', 'Подходы × повторы', 'Темп', 'Отдых', 'Запас' if with_rir else 'Как']]
    for it in items:
        if it['t'] == 'ex':
            rows.append([it['lab'], name(it), P.sets_text(it), tempo_or_hold(it), f'{it["rest"]} с' if it['rest'] else '—',
                         P.fmt_rir(it['rir']) if with_rir and it['rir'] else (it['note'] if not with_rir else '—')])
        elif it['t'] == 'cond':
            rows.append(['—', it['title'], '', '', '', ''])
    return pipe(rows)


def home_tables(cx):
    L = 1
    d1 = P.label_items(P.home1(cx, L))
    t1 = P.est_seconds(d1)
    rows = [['№', 'Упражнение', 'Объём', 'Темп или удержание', 'Отдых', 'Ключевое']]
    for it in d1:
        if it['t'] == 'ex':
            rows.append([it['lab'], name(it), P.sets_text(it), tempo_or_hold(it), f'{it["rest"]} с', it['note']])
        elif it['t'] == 'cond':
            rows.append(['—', it['title'], '', '', '', it['lines'][0] if it['lines'] else ''])
    s = f'#### День 1 — дом после смены, ≈ {round(t1 / 60)} мин\n\n' + pipe(rows)
    c = 1 if cx == 1 else 7
    d2 = P.label_items(P.home2(cx, L, c))
    t2 = P.est_seconds(d2)
    rows = [['№', 'Упражнение', 'Объём', 'Темп', 'Отдых', 'Ключевое']]
    for it in d2:
        if it['t'] == 'ex':
            rows.append([it['lab'], name(it), P.sets_text(it), tempo_or_hold(it), f'{it["rest"]} с', it['note']])

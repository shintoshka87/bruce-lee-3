def cycle_table():
    rows = [['Цикл', 'Дни', 'Недели', 'Блок · комплекс', 'Ур.', 'Волна', 'Зона 2 дома', 'Зона 2 в зале', 'Интервалы', 'Мешок', 'Отметки']]
    for c in range(1, P.NC + 1):
        t = P.info(c)
        d1, d4 = P.dn(c, 1), P.dn(c, 4)
        w1, w2 = P.week(d1), P.week(d4)
        mark = []
        if c == 1:
            mark.append('подбор весов')
        if t['first'] and c > 1:
            mark.append('смена упражнений')
        if t['test']:
            mark.append('тесты в День 3')
        if t['w'] == 'Т' and t['b'] in (2, 4, 5, 6):
            mark.append('4 × 4 — с допуском врача')
        rows.append([c, f'{d1}–{d4}', str(w1) if w1 == w2 else f'{w1}–{w2}', f'{t["b"]} · №{t["cx"]}', t['L'], t['w'],
                     f'{P.z2_home(c)} мин', f'{P.Z2_D3[t["L"]][t["w"]]} мин', P.interval_txt(t['b'], t['w']), P.bag_txt(t['b'], t['w'], c), ', '.join(mark) or '—'])
    return pipe(rows)



def wave_table(fn, cx, L):
    """Блок А: одна строка на упражнение, столбцы — волны."""
    by = {}
    order = []
    for w in ('Л', 'С', 'Т', 'Р'):
        for it in P.label_items(fn(cx, L, w)):
            key = it['lab']
            if key not in by:
                by[key] = {}
                order.append(key)
            by[key][w] = it
    rows = [['№', 'Упражнение', 'Л', 'С', 'Т', 'Р']]
    for key in order:
        cells = []
        nm = []
        for w in ('Л', 'С', 'Т', 'Р'):
            it = by[key][w]
            cells.append(P.sets_text(it) + ('' if name(it) == name(by[key]['Л']) else f' ({name(it).lower()})'))
        rows.append([key, name(by[key]['Л'])] + cells)
    return pipe(rows)


